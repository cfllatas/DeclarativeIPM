// Probe of the REAL Declare engine (the filter the agent applies: PMLogDeclareFilter), run headless on tiny hand-made traces.
// It prints truth tables so that the meaning of every operator is KNOWN, not assumed, before the bank defines "the right answer" for it.
//   DeclarativeIpmEval.exe --probe-semantics > <output>.md
using System.IO;
using System.Text;
using System.Text.Json;
using pm4h.data;
using pm4hlab.ext.tpaengine.declaregrammar;
using PMAppSVELTA.DeclarativeIPM;

namespace DeclarativeIpmEval;

public static class Probe
{
    /// <summary>true when the engine keeps the single trace; "SYN" when the expression does not parse; "ERR" on an exception.</summary>
    public static string Run(string expr, PMTrace t)
    {
        try
        {
            if (DeclarativeIPMValidation.SyntaxError(expr) != null) return "SYN";
            var log = new PMLog();
            log.addTrace(t);
            var res = new PMLogDeclareFilter { Expression = expr }.ProcessLog(new IPMLog[] { log });
            return res.First().Count() > 0 ? "1" : "0";
        }
        catch (Exception) { return "ERR"; }
    }

    static readonly DateTime T0 = new(2024, 1, 1, 8, 0, 0);

    /// <summary>A trace whose events are the letters of s; each event lasts 5 minutes and starts stepMin minutes after the previous one.</summary>
    public static PMTrace Make(string s, int stepMin = 10)
    {
        var t = new PMTrace { SampleId = s };
        for (int i = 0; i < s.Length; i++)
            t.InsertByStartTime(new PMEvent { SampleId = s, Start = T0.AddMinutes(i * stepMin), End = T0.AddMinutes(i * stepMin + 5), ActivityName = s[i].ToString() });
        return t;
    }

    static void Table(StringBuilder md, string title, string[] exprs, (string Label, PMTrace Trace)[] traces)
    {
        md.AppendLine($"### {title}\n");
        md.AppendLine("| Expression | " + string.Join(" | ", traces.Select(x => x.Label)) + " |");
        md.AppendLine("|---|" + string.Join("|", traces.Select(_ => "---")) + "|");
        foreach (var e in exprs)
            md.AppendLine($"| `{e}` | " + string.Join(" | ", traces.Select(x => Run(e, x.Trace))) + " |");
        md.AppendLine();
    }

    public static string Semantics()
    {
        var md = new StringBuilder();
        md.AppendLine("# Declare engine semantics (probed)\n");
        md.AppendLine("Generated by `DeclarativeIpmEval.exe --probe-semantics` against the real filter (`PMLogDeclareFilter`) on hand-made traces; `1` = the trace is kept, `0` = it is not, `SYN` = syntax error, `ERR` = exception. Trace `ABA` means three events A, B, A in that order.\n");

        string[] ts = { "", "A", "B", "C", "AB", "BA", "AAB", "ABB", "ABA", "BAB", "BBA", "AABB", "ABAB", "ABBA", "ACB", "CAB", "ABC" };
        var traces = ts.Select(s => (s == "" ? "∅" : s, Make(s))).ToArray();
        Table(md, "1. Existence, position and sequences", new[]
        {
            "'A'", "!'A'",
            "('A' > 'B')", "('A' >> 'B')", "('A' %> 'B')", "('A' %>> 'B')", "('A' > ? > 'B')", "('A' >> 'B' >> 'C')",
            "'A' & 'B'", "'A' | 'B'", "!('A' & 'B')", "!'A' & 'B'", "'A' & !'B'",
            "!('A' >> 'B')", "'A' & ('B' >> 'C')", "('A' >> 'B') | ('B' >> 'A')", "'B' & !('A' >> 'B')",
        }, traces);
        Table(md, "2. Declare templates between two events", new[]
        {
            "'A' -> 'B'", "'A' ->+ 'B'", "'A' ->* 'B'",
            "'B' <- 'A'", "'B' +<- 'A'", "'B' *<- 'A'",
            "'A' => 'B'", "'A' =>+ 'B'", "'A' =>* 'B'",
        }, traces);

        // time: A starts at 0 and lasts 5 min, B starts at 90 min and lasts 5 min
        var ab = Make("AB", 90);
        var abc = Make("ABC", 90);
        var one = Make("A", 90);
        Table(md, "3. Time intervals (trace AB: A at 0–5 min, B at 90–95 min; trace ABC: C at 180–185; trace A: one 5-minute event)", new[]
        {
            "('A' >> 'B')[-91m]", "('A' >> 'B')[-96m]", "('A' >> 'B')[-89m]", "('A' >> 'B')[91m-]", "('A' >> 'B')[89m-]", "('A' >> 'B')[1h-2h]", "('A' >> 'B')[-1h]", "('A' >> 'B')[2h-]",
            "('A' > 'B')[-2h]", "('A' >> 'B' >> 'C')[-3h]", "('A' >> 'B' >> 'C')[-181m]", "('A' >> 'B' >> 'C')[-186m]",
            "('A')[-6m]", "('A')[-4m]", "('A')[6m-]",
        }, new (string, PMTrace)[] { ("AB", ab), ("ABC", abc), ("A", one) });

        // trace variables, read through the REAL JSONL reader (so the value types are exactly the application's)
        var dir = Path.Combine(Path.GetTempPath(), "ipm-probe-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(dir);
        var file = Path.Combine(dir, "log.jsonl");
        var lines = new List<string> { "{\"_LogAttrs\":{\"Escenario\":\"probe\",\"_ECSVTraceCount\":3}}" };
        (string Id, string Attrs)[] cases =
        {
            ("t70F", "{\"Age\":70,\"Score\":2.5,\"Sex\":\"F\",\"Flag\":\"si\",\"Code\":\"3\"}"),
            ("t50M", "{\"Age\":50,\"Score\":7.25,\"Sex\":\"M\",\"Flag\":\"no\",\"Code\":\"10\"}"),
            ("t65F", "{\"Age\":65,\"Score\":2.5,\"Sex\":\"F\",\"Flag\":\"no_aplica\",\"Code\":\"3\"}"),
        };
        foreach (var (id, attrs) in cases)
            lines.Add("{\"trace_id\":\"" + id + "\",\"attrs\":" + attrs + ",\"events\":{\"00000000\":{\"base\":{\"ActivityName\":\"A\",\"start\":\"2024-01-01T08:00:00\",\"end\":\"2024-01-01T08:05:00\"},\"extra\":{}},\"00000001\":{\"base\":{\"ActivityName\":\"B\",\"start\":\"2024-01-01T09:00:00\",\"end\":\"2024-01-01T09:05:00\"},\"extra\":{}}}}");
        File.WriteAllLines(file, lines, new UTF8Encoding(false));
        var reader = new PMApp4Base.src.factories.JSONLLogReader { jsonlfile = pm4h.vio.VIOHelper.CreateIPMAppIO(file) };
        var loaded = reader.getLog().First();
        var vt = loaded.IterateTraces().Select(t => (t.SampleId, t)).ToArray();
        Table(md, "4. Trace variables (read by the real JSONL reader). Traces: t70F = {Age 70, Score 2.5, Sex F, Flag si, Code '3'}; t50M = {50, 7.25, M, no, '10'}; t65F = {65, 2.5, F, no_aplica, '3'}", new[]
        {
            "[Age > 65]", "[Age >= 65]", "[Age < 65]", "[Age <= 65]", "[Age == 65]", "[Age == '65']", "[Age != 65]", "[Age > '65']", "[Age > 6]",
            "[Score > 2.6]", "[Score >= 2.5]", "[Score == 2.5]", "[Score == '2.5']",
            "[Sex == 'F']", "[Sex != 'F']", "['Sex' == 'F']", "[Flag == 'si']", "[Flag != 'si']", "[Flag == 'no_aplica']",
            "[Code == '3']", "[Code == 3]", "[Code > 5]", "[Code > '5']", "[Code < 5]",
            "[Age > 60, Sex == 'F']", "[Age > 60 & Sex == 'F']", "[Age > 60 | Sex == 'M']", "[(Age > 60 | Sex == 'M') & Flag != 'no']", "[Age > 60] & [Sex == 'F']", "[Age > 60] | [Sex == 'M']",
            "[.Age > 65]",
            "[Sex == '#^F']", "[Sex == '#^M']",
            "'A' & [Age > 65]", "('A' >> 'B') & [Sex == 'F']", "('A' >> 'B')[Sex == 'F']", "('A' >> 'B')[Age > 65]",
        }, vt);
        // what the real reader hands to the engine: event sequence of a loaded trace and the @Start / @End names
        md.AppendLine("### 4b. Events of a trace as loaded by the real JSONL reader\n");
        foreach (var (id, t) in vt)
            md.AppendLine($"* `{id}`: " + string.Join(", ", t.Events.Select(e => $"`{e.ActivityName}` ({e.Start:HH:mm}–{e.End:HH:mm})")));
        md.AppendLine();
        
        try { Directory.Delete(dir, true); } catch { }

        // activity regular expressions and special names, on the letters traces
        Table(md, "5. Regular-expression names", new[]
        {
            "'#^A$'", "'#^[AB]$'", "'#^C'", "('#^A$' >> '#^B$')",
        }, traces);
        Probe2.Extra(md, ts);
        return md.ToString();
    }
}
